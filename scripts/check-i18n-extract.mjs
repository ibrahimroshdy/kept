#!/usr/bin/env node
// The catalogue-extraction gate (step-1 carry-over "Catalogue extraction has no gate", closed for
// good in step-3 T32): runs the real `lingui extract` CLI, with the web app's own config, into a
// scratch copy of the catalogues under .tmp/, and fails (exit 1) when
//   - the extract adds a message id the committed catalogues don't hold (a string was added to
//     the source and never extracted: a production build would show its hashed id), or
//   - a committed non-English catalogue has an empty translation for a message the source uses
//     (the Arabic UI would show English).
// The committed catalogues are never written. scripts/check-i18n.mjs checks the same through
// Lingui's API in memory (it runs in `pnpm lint`); this one goes through the CLI and the files,
// the way a developer's `pnpm --filter @kept/web i18n:extract` does, so a difference between the
// two paths can't hide a missing string. scripts/ci-local.sh runs it as the `catalogues` step.
//
//   node scripts/check-i18n-extract.mjs
import { spawnSync } from 'node:child_process';
import {
  cpSync,
  mkdirSync,
  mkdtempSync,
  readdirSync,
  readFileSync,
  rmSync,
  writeFileSync,
} from 'node:fs';
import { createRequire } from 'node:module';
import { join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const repo = fileURLToPath(new URL('..', import.meta.url));
const web = join(repo, 'apps/web');
const locales = join(web, 'src/locales');

/** A PO string literal's value: `"a\"b"` → `a"b`. */
function unquote(s) {
  return JSON.parse(s);
}

/**
 * The live entries of a PO file: key → translation. The key is `msgid`, or `msgctxt\u0004msgid`
 * when the entry has a context (Lingui's own key). The header (empty msgid) and obsolete `#~`
 * entries are left out. Multi-line strings are joined.
 */
export function parsePo(text) {
  const out = new Map();
  let entry = null;
  let field = null;
  const flush = () => {
    if (entry && entry.msgid !== undefined && entry.msgid !== '') {
      const key =
        entry.msgctxt !== undefined ? `${entry.msgctxt}\u0004${entry.msgid}` : entry.msgid;
      out.set(key, entry.msgstr ?? '');
    }
    entry = null;
    field = null;
  };
  for (const raw of text.split('\n')) {
    const line = raw.trim();
    if (line === '') {
      flush();
      continue;
    }
    if (line.startsWith('#')) {
      // A comment starts a new entry only if the previous one has its msgstr.
      if (entry?.msgstr !== undefined) flush();
      continue;
    }
    const m = /^(msgctxt|msgid|msgstr)\s+(".*")$/.exec(line);
    if (m) {
      if (m[1] === 'msgctxt' || (m[1] === 'msgid' && entry?.msgstr !== undefined)) flush();
      entry ??= {};
      field = m[1];
      entry[field] = unquote(m[2]);
      continue;
    }
    if (line.startsWith('"') && entry && field) {
      entry[field] += unquote(line);
    }
  }
  flush();
  return out;
}

/** Ids the fresh extract has that the committed catalogue doesn't. */
export function newIds(extracted, committed) {
  return [...extracted.keys()].filter((k) => !committed.has(k));
}

/** Ids the source uses (present in the fresh extract) whose committed translation is empty. */
export function emptyTranslations(extracted, committed) {
  return [...extracted.keys()].filter((k) => committed.has(k) && committed.get(k) === '');
}

const show = (key) => `  ${JSON.stringify(key.replace('\u0004', ' [context] '))}`;

function main() {
  const requireWeb = createRequire(join(web, 'package.json'));
  mkdirSync(join(repo, '.tmp'), { recursive: true });
  const scratch = mkdtempSync(join(repo, '.tmp/ci-i18n-'));
  try {
    const names = readdirSync(locales, { withFileTypes: true })
      .filter((d) => d.isDirectory())
      .map((d) => d.name)
      .sort();
    for (const l of names) {
      mkdirSync(join(scratch, l), { recursive: true });
      cpSync(join(locales, l, 'messages.po'), join(scratch, l, 'messages.po'));
    }
    // The web config with the catalogues' path moved to the scratch copy. Everything else
    // (locales, source locale, format, include and exclude) is the web app's own.
    const formatPo = pathToFileURL(requireWeb.resolve('@lingui/format-po')).href;
    const webConfig = pathToFileURL(join(web, 'lingui.config.ts')).href;
    const config = join(scratch, 'lingui.config.ts');
    writeFileSync(
      config,
      `// Generated by scripts/check-i18n-extract.mjs: apps/web's config, extracting into ${scratch}.
import base from ${JSON.stringify(webConfig)};
import { formatter } from ${JSON.stringify(formatPo)};
export default {
  ...base,
  rootDir: ${JSON.stringify(web)},
  format: formatter({ lineNumbers: false }),
  catalogs: base.catalogs.map((c) => ({
    ...c,
    path: ${JSON.stringify(`${scratch}/{locale}/messages`)},
    include: c.include.map((p) => ${JSON.stringify(`${web}/`)} + p),
  })),
};
`,
    );
    const lingui = join(web, 'node_modules/.bin/lingui');
    const run = spawnSync(lingui, ['extract', '--config', config], {
      cwd: web,
      encoding: 'utf8',
    });
    if (run.status !== 0) {
      console.error(run.stdout, run.stderr);
      console.error(`check-i18n-extract: lingui extract exited ${run.status}`);
      process.exit(1);
    }
    let failed = false;
    for (const l of names) {
      const committed = parsePo(readFileSync(join(locales, l, 'messages.po'), 'utf8'));
      const extracted = parsePo(readFileSync(join(scratch, l, 'messages.po'), 'utf8'));
      const added = newIds(extracted, committed);
      if (added.length > 0) {
        failed = true;
        console.error(
          `check-i18n-extract: extracting adds ${added.length} message(s) to ${l}/messages.po that aren't committed:`,
        );
        for (const k of added.slice(0, 40)) console.error(show(k));
      }
      if (l !== 'en') {
        const empty = emptyTranslations(extracted, committed);
        if (empty.length > 0) {
          failed = true;
          console.error(
            `check-i18n-extract: ${empty.length} empty translation(s) in ${l}/messages.po:`,
          );
          for (const k of empty.slice(0, 40)) console.error(show(k));
        }
      }
    }
    if (failed) {
      console.error(
        'check-i18n-extract: run `pnpm --filter @kept/web i18n:extract`, translate every new message in all five catalogues, and commit them.',
      );
      process.exit(1);
    }
    console.log(
      `check-i18n-extract: extracting adds nothing to ${names.join(', ')}; no empty translation.`,
    );
  } finally {
    rmSync(scratch, { recursive: true, force: true });
  }
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  main();
}
