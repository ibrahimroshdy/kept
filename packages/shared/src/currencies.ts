const BY_CODE: ReadonlyMap<string, IsoCurrency> = new Map(ISO_CURRENCIES.map((c) => [c.code, c]));

/** The ISO 4217 entry for `code`, or undefined when Kept does not know it. */
export function currencyInfo(code: string): IsoCurrency | undefined {
  return BY_CODE.get(code);
}

/** Minor units for `code`; 2 for a code outside the list (ISO 4217's common case). */
export function minorUnits(code: string): number {
  return BY_CODE.get(code)?.minorUnits ?? 2;
}
