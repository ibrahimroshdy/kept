/** More lines than this, and the row says how many and offers Show (#140). */
export const SUMMARY_LINES_INLINE = 5;

const KNOWN: ReadonlySet<string> = new Set(AUDIT_ACTIONS);

/** Whether `action` is one the server writes. */
export function isAuditAction(action: string): action is AuditAction {
  return KNOWN.has(action);
}
